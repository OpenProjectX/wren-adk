CREATE SCHEMA IF NOT EXISTS wrenai;
SET search_path TO wrenai;

CREATE TABLE categories (
    category_id   INTEGER PRIMARY KEY,
    name          VARCHAR(60)  NOT NULL,
    slug          VARCHAR(60)  NOT NULL UNIQUE,
    description   TEXT
);
COMMENT ON TABLE  categories IS 'Product catalogue categories.';

CREATE TABLE products (
    product_id    INTEGER PRIMARY KEY,
    category_id   INTEGER NOT NULL REFERENCES categories(category_id),
    sku           VARCHAR(24)  NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    unit_cost     NUMERIC(10,2) NOT NULL,
    stock_qty     INTEGER      NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL
);
COMMENT ON TABLE  products            IS 'Sellable items in the catalogue.';
COMMENT ON COLUMN products.unit_price IS 'List price per unit, USD.';
COMMENT ON COLUMN products.unit_cost  IS 'Cost of goods per unit, USD. Margin = unit_price - unit_cost.';

CREATE TABLE customers (
    customer_id   INTEGER PRIMARY KEY,
    email         VARCHAR(120) NOT NULL UNIQUE,
    first_name    VARCHAR(60)  NOT NULL,
    last_name     VARCHAR(60)  NOT NULL,
    country       VARCHAR(2)   NOT NULL,
    city          VARCHAR(60),
    segment       VARCHAR(12)  NOT NULL,
    signup_date   DATE         NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);
COMMENT ON TABLE  customers         IS 'Registered shoppers.';
COMMENT ON COLUMN customers.country IS 'ISO 3166-1 alpha-2 country code.';
COMMENT ON COLUMN customers.segment IS 'Lifecycle segment: consumer, smb, enterprise.';

CREATE TABLE addresses (
    address_id    INTEGER PRIMARY KEY,
    customer_id   INTEGER NOT NULL REFERENCES customers(customer_id),
    line1         VARCHAR(120) NOT NULL,
    city          VARCHAR(60)  NOT NULL,
    postal_code   VARCHAR(16),
    country       VARCHAR(2)   NOT NULL,
    is_default    BOOLEAN      NOT NULL DEFAULT FALSE
);
COMMENT ON TABLE addresses IS 'Shipping addresses; a customer may have several.';

CREATE TABLE orders (
    order_id       INTEGER PRIMARY KEY,
    customer_id    INTEGER NOT NULL REFERENCES customers(customer_id),
    address_id     INTEGER          REFERENCES addresses(address_id),
    order_date     DATE         NOT NULL,
    ordered_at     TIMESTAMP    NOT NULL,
    status         VARCHAR(12)  NOT NULL,
    channel        VARCHAR(12)  NOT NULL,
    currency       VARCHAR(3)   NOT NULL DEFAULT 'USD',
    shipping_fee   NUMERIC(10,2) NOT NULL,
    discount_total NUMERIC(10,2) NOT NULL,
    total_amount   NUMERIC(12,2) NOT NULL
);
COMMENT ON TABLE  orders              IS 'Customer orders, one row per order.';
COMMENT ON COLUMN orders.status       IS 'pending, processing, shipped, delivered, cancelled, returned.';
COMMENT ON COLUMN orders.channel      IS 'Acquisition channel: web, mobile_app, marketplace.';
COMMENT ON COLUMN orders.total_amount IS 'Gross order value incl. shipping, net of discounts, USD.';

CREATE TABLE order_items (
    order_item_id INTEGER PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders(order_id),
    product_id    INTEGER NOT NULL REFERENCES products(product_id),
    quantity      INTEGER NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    discount_pct  NUMERIC(5,4)  NOT NULL,
    line_total    NUMERIC(12,2) NOT NULL
);
COMMENT ON TABLE  order_items              IS 'Line items belonging to an order.';
COMMENT ON COLUMN order_items.discount_pct IS 'Fractional discount, 0.10 = 10% off.';
COMMENT ON COLUMN order_items.line_total   IS 'quantity * unit_price * (1 - discount_pct), USD.';

CREATE TABLE payments (
    payment_id    INTEGER PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders(order_id),
    method        VARCHAR(16) NOT NULL,
    status        VARCHAR(12) NOT NULL,
    amount        NUMERIC(12,2) NOT NULL,
    paid_at       TIMESTAMP
);
COMMENT ON TABLE  payments        IS 'Payment attempts against orders.';
COMMENT ON COLUMN payments.method IS 'card, paypal, bank_transfer, gift_card.';
COMMENT ON COLUMN payments.status IS 'captured, refunded, failed, pending.';

CREATE TABLE reviews (
    review_id     INTEGER PRIMARY KEY,
    product_id    INTEGER NOT NULL REFERENCES products(product_id),
    customer_id   INTEGER NOT NULL REFERENCES customers(customer_id),
    rating        INTEGER NOT NULL,
    title         VARCHAR(120),
    body          TEXT,
    created_at    TIMESTAMP NOT NULL
);
COMMENT ON TABLE  reviews        IS 'Product reviews left by customers.';
COMMENT ON COLUMN reviews.rating IS 'Star rating, 1 (worst) to 5 (best).';

CREATE INDEX idx_orders_customer   ON orders(customer_id);
CREATE INDEX idx_orders_date       ON orders(order_date);
CREATE INDEX idx_items_order       ON order_items(order_id);
CREATE INDEX idx_items_product     ON order_items(product_id);
CREATE INDEX idx_payments_order    ON payments(order_id);

